// 제목에 구체적인 숫자(금액·비율·날짜·인원)가 있으면 카드로 만들기 좋음
const FIGURE = /\d+(?:\.\d+)?\s?(?:억|만\s?원|만원|천만|조|%|％|%p|배|가구|세대|명|대\s?1|평|㎡|개월|년|월|일)/g;
// 독자에게 직접 와닿지 않는 글 (업계 동정, 실적, 인사, 행사)
const DULL = /실적|영업이익|수주|MOU|협약|개최|참석|방문|수상|출시|인사|부고|기념|캠페인|봉사|주가|특징주|공시\b/;

/** 0~100. 스레드에 올리기 좋은 정도 (독자 관심 + 구체적 수치) */
export function threadPick(title) {
  let w = 0;
  for (const [re, v] of INTEREST) if (re.test(title)) w += v;
  const figures = (title.match(FIGURE) || []).length;
  w += Math.min(figures, 2) * 0.15;
  if (DULL.test(title)) w -= 0.4;
  return Math.round(Math.max(0, Math.min(1, w)) * 100);
}
