export function tagsOf(title) {
  return TOPICS.filter((t) => t.re.test(title)).map((t) => t.id);
}

export function isRelevant(title) {
  return RELEVANT.test(title);
}

/** 0~1 */
export function keywordWeight(title) {
  let w = 0;
  for (const [re, v] of WEIGHTS) if (re.test(title)) w += v;
  return Math.min(1, w);
}

